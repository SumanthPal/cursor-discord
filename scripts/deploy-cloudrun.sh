#!/usr/bin/env bash
# Deploy cursor-discord to Cloud Run (min=1, max=1, always-on CPU).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

: "${GCP_PROJECT:?Set GCP_PROJECT}"
: "${GCP_REGION:=us-central1}"
SERVICE="${SERVICE:-cursor-discord}"
REPO="${ARTIFACT_REPO:-cursor-discord}"
IMAGE="${GCP_REGION}-docker.pkg.dev/${GCP_PROJECT}/${REPO}/${SERVICE}"

echo "Project=${GCP_PROJECT} Region=${GCP_REGION} Service=${SERVICE}"

gcloud config set project "${GCP_PROJECT}" >/dev/null

# Artifact Registry repo (idempotent)
if ! gcloud artifacts repositories describe "${REPO}" --location="${GCP_REGION}" >/dev/null 2>&1; then
  gcloud artifacts repositories create "${REPO}" \
    --repository-format=docker \
    --location="${GCP_REGION}" \
    --description="cursor-discord images"
fi

# Secrets (create empty placeholders only if missing — fill via console/CLI)
ensure_secret() {
  local name="$1"
  if ! gcloud secrets describe "${name}" >/dev/null 2>&1; then
    echo "Creating secret ${name} (add a version before first traffic):"
    echo "  printf '%s' 'VALUE' | gcloud secrets versions add ${name} --data-file=-"
    gcloud secrets create "${name}" --replication-policy=automatic
  fi
}

ensure_secret discord-token
ensure_secret discord-client-id
ensure_secret cursor-api-key

# Grant Cloud Run runtime SA access to secrets
PROJECT_NUMBER="$(gcloud projects describe "${GCP_PROJECT}" --format='value(projectNumber)')"
RUNTIME_SA="${RUNTIME_SA:-${PROJECT_NUMBER}-compute@developer.gserviceaccount.com}"
for s in discord-token discord-client-id cursor-api-key; do
  gcloud secrets add-iam-policy-binding "${s}" \
    --member="serviceAccount:${RUNTIME_SA}" \
    --role="roles/secretmanager.secretAccessor" \
    --quiet >/dev/null || true
done

TAG="$(git rev-parse --short HEAD 2>/dev/null || date +%Y%m%d%H%M%S)"
FULL_IMAGE="${IMAGE}:${TAG}"

echo "Building ${FULL_IMAGE}"
# Async + poll: waiting with log streaming fails for SAs that can't read the
# default Cloud Build logs bucket (even with --suppress-logs).
BUILD_ID="$(gcloud builds submit --tag "${FULL_IMAGE}" . --async --format='value(id)')"
echo "Cloud Build ${BUILD_ID}"
STATUS=""
for _ in $(seq 1 60); do
  STATUS="$(gcloud builds describe "${BUILD_ID}" --format='value(status)')"
  case "${STATUS}" in
    SUCCESS) break ;;
    FAILURE|INTERNAL_ERROR|TIMEOUT|CANCELLED|EXPIRED)
      echo "Cloud Build ${BUILD_ID} failed: ${STATUS}" >&2
      exit 1
      ;;
  esac
  sleep 5
done
if [[ "${STATUS}" != "SUCCESS" ]]; then
  echo "Timed out waiting for Cloud Build ${BUILD_ID} (last=${STATUS:-unknown})" >&2
  exit 1
fi

# PROJECTS_JSON from local file if present
PROJECTS_JSON_VALUE="${PROJECTS_JSON:-}"
if [[ -z "${PROJECTS_JSON_VALUE}" && -f projects.yaml ]]; then
  PY_BIN="${ROOT}/.venv/bin/python"
  if [[ ! -x "${PY_BIN}" ]]; then PY_BIN="python3"; fi
  PROJECTS_JSON_VALUE="$("${PY_BIN}" - <<'PY'
import json, pathlib, sys
try:
    import yaml
except ImportError:
    sys.exit(0)
data = yaml.safe_load(pathlib.Path("projects.yaml").read_text()) or {}
print(json.dumps(data, separators=(",", ":")))
PY
)"
fi

ENV_FILE="$(mktemp)"
cleanup() { rm -f "${ENV_FILE}"; }
trap cleanup EXIT

{
  echo "# generated by deploy-cloudrun.sh"
  if [[ -n "${PROJECTS_JSON_VALUE}" ]]; then
    # YAML double-quoted string; escape embedded quotes/backslashes
    python3 - "${PROJECTS_JSON_VALUE}" <<'PY'
import json, sys
val = sys.argv[1]
print("PROJECTS_JSON:", json.dumps(val))
PY
  fi
  if [[ -n "${ALLOWED_USER_IDS:-}" ]]; then
    echo "ALLOWED_USER_IDS: \"${ALLOWED_USER_IDS}\""
  fi
  if [[ -n "${ALLOWED_GUILD_IDS:-}" ]]; then
    echo "ALLOWED_GUILD_IDS: \"${ALLOWED_GUILD_IDS}\""
  fi
  if [[ -n "${SUPERUSER_IDS:-}" ]]; then
    echo "SUPERUSER_IDS: \"${SUPERUSER_IDS}\""
  fi
  if [[ -n "${CURSOR_ROLE_NAME:-}" ]]; then
    echo "CURSOR_ROLE_NAME: \"${CURSOR_ROLE_NAME}\""
  fi
  if [[ -n "${CURSOR_MODEL:-}" ]]; then
    echo "CURSOR_MODEL: \"${CURSOR_MODEL}\""
  fi
} > "${ENV_FILE}"

DEPLOY_ARGS=(
  gcloud run deploy "${SERVICE}"
  --image="${FULL_IMAGE}"
  --region="${GCP_REGION}"
  --platform=managed
  --allow-unauthenticated
  --min-instances=1
  --max-instances=1
  --cpu=1
  --memory=512Mi
  --no-cpu-throttling
  --timeout=3600
  --port=8080
  --set-secrets="DISCORD_TOKEN=discord-token:latest,CURSOR_API_KEY=cursor-api-key:latest,DISCORD_CLIENT_ID=discord-client-id:latest"
)

if [[ -s "${ENV_FILE}" ]] && grep -qv '^#' "${ENV_FILE}"; then
  DEPLOY_ARGS+=(--env-vars-file="${ENV_FILE}")
fi

"${DEPLOY_ARGS[@]}"

echo "Deployed. Ensure secrets have versions, then invite the Discord bot."
gcloud run services describe "${SERVICE}" --region="${GCP_REGION}" --format='value(status.url)'
